"""Deterministic QUALITY_STATUS renderer (Round-2 P1-3 / Standard §4).

Renders the central repo's quality dashboard FROM FACTS: the cohort manifest,
the track catalog, the canonical store, and the live ``check_drift`` findings.
Deterministic by construction — it uses the cohort CONTRACT commit + committed
data, NEVER the wall clock and NEVER the moving working-tree HEAD — so the file
is byte-stable and drift-checkable (``--check``). ``QUALITY_STATUS.md`` is a
generated artifact; DO NOT hand-edit it (regenerate after any hub/contract
change; CI enforces freshness).
"""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

from . import hub


def render_quality_status(repo_root: Path | str) -> str:
    """Render the central QUALITY_STATUS.md as a deterministic markdown string."""
    repo = Path(repo_root)
    cohort = json.loads((repo / "contracts" / "cohort.json").read_text(encoding="utf-8"))
    tracks = json.loads((repo / "contracts" / "tracks.json").read_text(encoding="utf-8"))
    canonical = json.loads((repo / "hub" / "canonical_results.json").read_text(encoding="utf-8"))
    rows = canonical.get("results", [])
    status_dist = dict(Counter(r.get("status", "valid") for r in rows))
    imports = hub.load_imports_store(repo / "hub")
    findings = hub.check_drift(canonical_rows=rows, imports=imports)
    fbyk = Counter(f["kind"] for f in findings)

    L: list[str] = []
    L.append("# QUALITY_STATUS — OmniDocBench-ROCm (central authority)")
    L.append("")
    L.append("> Auto-generated by `python scripts/render_quality_status.py` — **DO NOT EDIT**.")
    L.append("> Regenerate after any hub/contract change; freshness is CI-checked (`render-quality-status --check`).")
    L.append(f"> Contract commit: `{cohort['central_commit']}` ({cohort['central_commit_date']}).")
    L.append("")
    L.append("## Cohort")
    L.append(f"- cohort_id: `{cohort['cohort_id']}`")
    L.append(f"- contract_release / conformance_release: `{cohort['contract_release']}` / `{cohort['conformance_release']}`")
    L.append(f"- standard_version: {cohort['standard_version']}")
    L.append(f"- artifact_schema: `{cohort['artifact_schema']['$id']}` "
             f"(content sha256 `{cohort['artifact_schema']['sha256'][:12]}…`)")
    L.append(f"- conformance_profiles: {', '.join(cohort['conformance_profiles'])}")
    L.append(f"- result_identity: {cohort['result_identity']}")
    L.append("")
    L.append("## Comparison tracks (contracts/tracks.json)")
    for t in tracks["tracks"]:
        d = t["dataset"]
        psh = d.get("page_set_hash", "?")
        psh_short = (psh[:19] + "…") if isinstance(psh, str) and psh.startswith("sha256:") else psh
        L.append(f"- `{t['track_id']}` — subset `{d['subset']}`, pages `{d.get('page_count')}`, "
                 f"page_set_hash `{psh_short}`")
    L.append("")
    L.append("## Hub / canonical store")
    L.append(f"- results: **{len(rows)}** "
             f"({', '.join(f'{v} {k}' for k, v in sorted(status_dist.items()))})")
    L.append(f"- check_drift findings: **{len(findings)}**")
    if findings:
        for kind, n in sorted(fbyk.items()):
            rids = [str(f.get("result_id")) for f in findings if f["kind"] == kind]
            L.append(f"  - **{kind}: {n}** — `{rids}`")
        L.append("  - Reported for a maintainer decision (validators DETECT, they do not auto-fix). "
                 "See the zone audit for the resolution options.")
    else:
        L.append("  - none")
    L.append("")
    L.append("## Honesty")
    L.append("- GPU inference / score / inference / cross-hardware reproduction: **NOT_RUN** in this "
             "environment (no GPU). Never reported as passed.")
    L.append("- producer_assurance and platform_review are SPLIT; no auto-promotion of either.")
    L.append("")
    L.append("## Central gates")
    L.append("Run via `make ci`: `validate_registry`, `registry generate --check`, "
             "`generate_registry --check`, `check_brand`, `check_license_class`, `check_result_ids`, "
             "`build`, `pytest`, `render-quality-status --check`.")
    L.append("")
    L.append("## Generation")
    L.append("- generator: `omnidocbench_rocm.quality_status.render_quality_status` "
             "(`python scripts/render_quality_status.py`).")
    L.append("- derived from: `contracts/cohort.json`, `contracts/tracks.json`, "
             "`hub/canonical_results.json` + `check_drift`. No wall-clock input.")
    return "\n".join(L) + "\n"


def check_quality_status(repo_root: Path | str) -> list[str]:
    """Drift problems with the committed QUALITY_STATUS.md (empty = up to date)."""
    repo = Path(repo_root)
    target = repo / "QUALITY_STATUS.md"
    expected = render_quality_status(repo)
    if not target.exists():
        return ["QUALITY_STATUS.md missing — run scripts/render_quality_status.py"]
    if target.read_text(encoding="utf-8") != expected:
        return ["QUALITY_STATUS.md is stale — run scripts/render_quality_status.py"]
    return []
